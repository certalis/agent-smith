import { defineScenario } from "./harness/scenario";
import {
	drainControl,
	poolRequest,
	poolWire,
	providerChunk,
	wireProxyKey,
} from "./harness/wire-fixture";

export default defineScenario({
	...poolWire,
	name: "deploy drain counts an existing stream until completion and rejects new ingress",
	upstream: [
		{
			id: "active-stream",
			times: 1,
			status: 200,
			sse: [{ body: providerChunk }],
			keepOpen: "after-chunks",
		},
		{ status: 200, json: { resumed: true } },
	],
	steps: [
		{ ...poolRequest, id: "existing", waitForCompletion: false },
		{ type: "wait-for-client-chunk", id: "existing" },
		{ ...drainControl, method: "POST", id: "paused" },
		{ ...drainControl, method: "GET", id: "active-status" },
		{ ...poolRequest, id: "rejected" },
		...(["tcp", "unix"] as const).map((transport) => ({
			...poolRequest,
			transport,
			id: "rejected",
			headers: { "x-api-key": wireProxyKey },
		})),
		{
			type: "request",
			id: "paused-capacity",
			method: "GET",
			path: "/api/pool-status?provider=claude-code",
			body: "",
			headers: { "x-api-key": wireProxyKey },
		},
		{
			type: "request",
			id: "health",
			method: "GET",
			path: "/health",
			body: "",
			headers: { "x-api-key": wireProxyKey },
		},
		{
			type: "assert",
			assertions: [
				{
					id: "pause-does-not-end-existing-stream-or-contact-provider",
					type: "upstream",
					count: 1,
					closed: 0,
					responsesEnded: 0,
				},
			],
		},
		{ type: "release", id: "active-stream" },
		{ type: "await", id: "existing" },
		{ ...drainControl, method: "GET", id: "empty-status" },
		{ ...drainControl, method: "DELETE", id: "resumed" },
		{
			type: "request",
			id: "resumed-capacity",
			method: "GET",
			path: "/api/pool-status?provider=claude-code",
			body: "",
			headers: { "x-api-key": wireProxyKey },
		},
		{ ...poolRequest, id: "new-after-resume" },
	],
	assertions: [
		{
			id: "admin-starts-drain",
			type: "client",
			request: "paused",
			status: 200,
		},
		{
			id: "status-counts-the-unfinished-response",
			type: "client",
			request: "active-status",
			status: 200,
			jsonPath: { path: "activeRequests", value: 1 },
		},
		{
			id: "all-new-inference-receives-retryable-rejection",
			type: "client",
			request: "rejected",
			statuses: [503, 503, 503],
			header: { name: "retry-after", value: "30" },
		},
		{
			id: "paused-scheduler-sees-retryable-unavailability",
			type: "client",
			request: "paused-capacity",
			status: 503,
			header: { name: "retry-after", value: "30" },
		},
		{
			id: "resumed-scheduler-can-read-capacity",
			type: "client",
			request: "resumed-capacity",
			status: 200,
		},
		{
			id: "health-stays-usable",
			type: "client",
			request: "health",
			status: 200,
		},
		{
			id: "existing-stream-finishes-with-identical-body",
			type: "client",
			request: "existing",
			status: 200,
			body: providerChunk,
		},
		{
			id: "status-excludes-itself-after-stream-completion",
			type: "client",
			request: "empty-status",
			jsonPath: { path: "activeRequests", value: 0 },
		},
		{
			id: "status-reports-no-websockets",
			type: "client",
			request: "empty-status",
			jsonPath: { path: "activeWebSockets", value: 0 },
		},
		{
			id: "admin-resumes-serving",
			type: "client",
			request: "resumed",
			status: 200,
			jsonPath: { path: "draining", value: false },
		},
		{
			id: "explicit-resume-admits-new-work",
			type: "client",
			request: "new-after-resume",
			status: 200,
		},
		{
			id: "only-existing-and-resumed-work-reach-provider",
			type: "upstream",
			count: 2,
			bodyIdentical: poolRequest.body,
		},
	],
});
