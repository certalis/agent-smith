import {
	confirm,
	disconnect,
	enrollmentConfig,
	enrollmentEnvironment,
	issue,
	profileReply,
	publicHeaders,
	readAccounts,
	readRouting,
	start,
	tokenReply,
	verify,
} from "./harness/enrollment-fixture";
import { defineScenario } from "./harness/scenario";

export default defineScenario({
	name: "private enrollment can disconnect and repeat twice without removing another seat",
	environment: enrollmentEnvironment,
	config: enrollmentConfig,
	claudeOAuth: true,
	fleet: [{ name: "untouched", accountUuid: "existing-seat" }],
	upstream: [
		tokenReply,
		{ ...profileReply(), times: 2 },
		profileReply({ uuid: "wrong-seat", email: "other@example.test" }),
	],
	steps: [
		issue("first", {
			name: "temporary-owner",
			email: "owner@example.test",
			contactEmail: "remind@example.test",
			slackUserId: "U0123456789",
		}),
		start("first"),
		verify("first"),
		{
			...disconnect("first", "second", false),
			id: "wrongKind",
			body: '{"token":"{{firstConfirm}}"}',
		},
		confirm("first", true),
		{
			...disconnect("first", "second", false),
			id: "wrongOrigin",
			headers: { ...publicHeaders, origin: "https://evil.example" },
		},
		disconnect("first", "second"),
		readAccounts("afterFirst"),
		readRouting("firstRouting"),
		start("second"),
		verify("second"),
		confirm("second", true),
		{ ...disconnect("first", "unused", false), id: "staleRemoval" },
		readAccounts("stillConnected"),
		disconnect("second", "third"),
		start("third"),
		verify("third", false),
		{ type: "restart" },
		readAccounts("afterRestart"),
		readRouting("afterRouting"),
	],
	assertions: [
		{
			id: "consent-capability-cannot-remove",
			type: "client",
			request: "wrongKind",
			status: 410,
		},
		{
			id: "wrong-origin-cannot-remove-or-consume",
			type: "client",
			request: "wrongOrigin",
			status: 403,
		},
		{
			id: "first-removal-succeeded",
			type: "client",
			request: "first-disconnect",
			status: 200,
			jsonPath: { path: "disconnected", value: true },
		},
		{
			id: "first-credentials-deleted",
			type: "client",
			request: "afterFirst",
			jsonPath: { path: "length", value: 1 },
		},
		{
			id: "first-membership-removed",
			type: "client",
			request: "firstRouting",
			jsonPath: { path: "allowlistedAccountUuids", value: ["existing-seat"] },
		},
		{
			id: "same-seat-can-reenroll",
			type: "client",
			request: "second-confirm",
			status: 200,
		},
		{
			id: "old-token-cannot-remove-new-account",
			type: "client",
			request: "staleRemoval",
			status: 410,
		},
		{
			id: "reenrolled-account-survives-stale-token",
			type: "client",
			request: "stillConnected",
			jsonPath: { path: "length", value: 2 },
		},
		{
			id: "retry-preserves-operator-label",
			type: "client",
			request: "stillConnected",
			bodyIncludes: '"name":"temporary-owner"',
		},
		{
			id: "second-removal-succeeded",
			type: "client",
			request: "second-disconnect",
			status: 200,
		},
		{
			id: "retry-preserves-email-restriction",
			type: "client",
			request: "third-verify",
			status: 400,
		},
		{
			id: "removal-survives-server-restart",
			type: "client",
			request: "afterRestart",
			jsonPath: { path: "length", value: 1 },
		},
		{
			id: "non-target-seat-preserved",
			type: "client",
			request: "afterRestart",
			jsonPath: { path: "0.name", value: "untouched" },
		},
		{
			id: "second-membership-removed",
			type: "client",
			request: "afterRouting",
			jsonPath: { path: "allowlistedAccountUuids", value: ["existing-seat"] },
		},
		{
			id: "routing-stays-disabled",
			type: "client",
			request: "afterRouting",
			jsonPath: { path: "enabled", value: false },
		},
		{
			id: "owner-cap-preserved",
			type: "client",
			request: "afterRouting",
			jsonPath: { path: "maxUsage", value: 0.85 },
		},
		{
			id: "admission-cap-preserved",
			type: "client",
			request: "afterRouting",
			jsonPath: { path: "admissionCap", value: 3 },
		},
		{ id: "only-login-calls-provider", type: "upstream", count: 6 },
	],
});
