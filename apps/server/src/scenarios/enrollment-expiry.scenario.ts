import {
	confirm,
	enrollmentEnvironment,
	issue,
	oauthReplies,
	publicHeaders,
	readAccounts,
	start,
	verify,
} from "./harness/enrollment-fixture";
import { defineScenario } from "./harness/scenario";

export default defineScenario({
	name: "private enrollment revokes restarted reissued and expired capabilities",
	environment: enrollmentEnvironment,
	claudeOAuth: true,
	fleet: [],
	upstream: oauthReplies,
	steps: [
		issue("restarted"),
		{ type: "restart" },
		{ ...start("restarted"), capture: undefined },
		issue("old", { name: "reserved" }),
		issue("new", { name: "reserved" }),
		{ ...start("old"), capture: undefined },
		{
			...start("new"),
			id: "wrongOrigin",
			capture: undefined,
			headers: { ...publicHeaders, origin: "https://evil.example" },
		},
		{
			...start("new"),
			id: "oversized",
			capture: undefined,
			body: JSON.stringify({
				token: "{{newInvite}}",
				padding: "x".repeat(8192),
			}),
		},
		start("new"),
		{ type: "advance", by: "10m" },
		verify("new", false),
		issue("expired"),
		{ type: "advance", by: "24h" },
		{ ...start("expired"), capture: undefined },
		issue("confirm"),
		start("confirm"),
		verify("confirm"),
		{ type: "advance", by: "10m" },
		confirm("confirm"),
		readAccounts("accounts"),
		{ ...issue("bounded"), count: 101, capture: undefined },
		{ type: "advance", by: "24h" },
		issue("afterPrune"),
	],
	assertions: [
		...[
			"restarted-start",
			"old-start",
			"new-verify",
			"expired-start",
			"confirm-confirm",
		].map((request) => ({
			id: `${request}-revoked`,
			type: "client" as const,
			request,
			status: 410,
		})),
		{
			id: "cross-origin-refused",
			type: "client",
			request: "wrongOrigin",
			status: 403,
		},
		{
			id: "oversized-body-refused",
			type: "client",
			request: "oversized",
			status: 413,
		},
		{
			id: "invalid-requests-did-not-consume-valid-link",
			type: "client",
			request: "new-start",
			status: 200,
		},
		{
			id: "expired-confirmation-never-saves",
			type: "client",
			request: "accounts",
			body: "[]",
		},
		{
			id: "pending-invitations-bounded",
			type: "client",
			request: "bounded",
			unorderedStatuses: [...Array<number>(100).fill(201), 429],
		},
		{
			id: "expired-invitations-release-capacity",
			type: "client",
			request: "afterPrune",
			status: 201,
		},
		{ id: "only-fresh-flow-calls-provider", type: "upstream", count: 2 },
	],
});
